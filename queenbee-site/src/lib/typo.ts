/**
 * Типографика при сборке: неразрывный пробел после коротких слов и перед длинным тире,
 * «ёлочки» вместо прямых кавычек. Строки прогоняются один раз при загрузке модуля
 * (и в пререндере), поэтому в HTML уже стоят правильные символы.
 */
const SHORT =
  /(^|[\s («„])(а|в|во|и|к|ко|о|об|от|с|со|у|на|по|за|из|до|не|но|ни|мы|вы|я|же|ли|бы|для|при|без|как|что|это|до|то)\s+/gi;

export function typo(s: string): string {
  let out = s.replace(/"([^"]*)"/g, "«$1»").replace(/\s+—\s+/g, " — ").replace(/\s+–\s+/g, " — ");
  // два прохода — для идущих подряд коротких слов («и в нашем»)
  for (let i = 0; i < 2; i++) out = out.replace(SHORT, (_m, pre: string, w: string) => `${pre}${w} `);
  return out;
}
