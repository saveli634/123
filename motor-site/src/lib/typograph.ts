/**
 * Русская типографика для строк сайта.
 * Применяется при сборке ко всем строковым литералам в src/content/* и src/config.ts
 * (см. scripts/typograph-plugin.ts), поэтому в разметку попадает уже готовый текст.
 *
 * Что делает:
 *  — неразрывный пробел после предлогов, союзов и коротких слов («в цехе», «и сборка»);
 *  — неразрывный пробел перед тире и частицами (ли, же, бы);
 *  — «слово 200» → «слово 200» (модель и номер не разрываются);
 *  — разряды чисел: «34 000» → «34 000»;
 *  — дефис в окружении пробелов → длинное тире, «...» → «…».
 * Строки без пробелов (адреса ссылок, идентификаторы) не меняются.
 */
const NBSP = " ";

const SHORT = [
  "а", "в", "во", "и", "й", "к", "ко", "о", "об", "обо", "с", "со", "у", "я",
  "не", "ни", "на", "за", "до", "из", "изо", "от", "ото", "по", "под", "подо",
  "при", "про", "для", "без", "безо", "над", "надо", "но", "да", "или", "что",
  "как", "мы", "вы", "он", "все", "всё", "это", "нас", "вас", "наш", "ваш",
].join("|");

const reShort = new RegExp(`(^|[\\s«„(\\u00A0—])(${SHORT}) +(?=[^\\s])`, "giu");
const reParticle = / +(ли|же|бы|ль|ж|б)(?=[\s.,!?…:;)»]|$)/gu;

export function typograph(input: string): string {
  if (!/\s/.test(input) && !input.includes("...")) return input;
  let s = input;
  s = s.replace(/\.\.\./g, "…");
  s = s.replace(/ +- +/g, ` — `);
  // Тире не начинает строку
  s = s.replace(/ +—/g, `${NBSP}—`);
  // Короткие слова прилипают к следующему (два прохода — для цепочек «и в», «не на»)
  s = s.replace(reShort, `$1$2${NBSP}`);
  s = s.replace(reShort, `$1$2${NBSP}`);
  s = s.replace(reParticle, `${NBSP}$1`);
  // Модель и номер, номер и единица: «Cruiser 200», «TLC 200»
  s = s.replace(/([A-Za-zА-Яа-яЁё]) +(\d)/g, `$1${NBSP}$2`);
  // Разряды: «34 000»
  s = s.replace(/(\d) +(?=\d{3}(?!\d))/g, `$1${NBSP}`);
  // Разделитель «·» не уходит в начало строки
  s = s.replace(/ +·/g, `${NBSP}·`);
  return s;
}
